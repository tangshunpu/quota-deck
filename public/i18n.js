 function t(text, values={}) {
  let result=language==='en'?(EN[text]??text):text;
  return String(result??'').replace(/\{(\w+)\}/g,(match,name)=>values[name]??match);
 }
 function dynamic(text) {
  if(!text||language!=='en')return text??'';
  if(EN[text])return EN[text];
  if(text.endsWith('；显示上次读数'))return dynamic(text.slice(0,-'；显示上次读数'.length))+'; '+t('显示上次读数');
  let match=text.match(/^(\d+(?:\.\d+)?) (天额度|小时窗口|分钟窗口)$/);
  if(match)return match[1]+({'天额度':'-day quota','小时窗口':'-hour window','分钟窗口':'-minute window'}[match[2]]);
  match=text.match(/^额度服务暂不可用（HTTP (\d+)）$/);
  if(match)return t('额度服务暂不可用（HTTP {code}）',{code:match[1]});
  match=text.match(/^(东北|东南|西北|西南|东|南|西|北)风\s*(.*)$/);
  if(match)return ({东北:'NE',东南:'SE',西北:'NW',西南:'SW',东:'E',南:'S',西:'W',北:'N'}[match[1]])+' '+match[2].replace('级',' Bft');
  return text;
 }
